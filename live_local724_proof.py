#!/usr/bin/env python3
"""live_local724_proof.py — LOCAL-724 live proof on the OWN isolated stack.

Proves, against local724-postgres-2-1 (host :55433) and local724-map-delivery-1
(host :55005) — NOT the shared audioura-* stack, and with NO launchd tick
running in this project — that:

  * a new ORIGINAL tour is RATED in the serving path (store_audio_tour) BEFORE it
    becomes listable, so its content_rating/review_status are already set the
    moment it first appears in /tours-near (items 1 & 2);
  * a tour whose only mature content is AFTER character 24,000 rates mature
    (item 3);
  * editing a tour's text re-rates it (item 4).

It calls the REAL serving-path function tour_orchestrator_service.store_audio_tour
(the exact function the orchestrator runs after generation), which makes a REAL
OpenAI rating call (key read from the environment, never written). Tour TEXT is
generated by a real model call too (generate_proof_tour), so this is a generation
run, not a canned fixture. Row counts are printed before and after.

Run with the isolated DB env:
  DB_HOST=localhost DB_PORT=55433 OPENAI_API_KEY=... python3 live_local724_proof.py
"""
import io
import os
import sys
import json
import time
import urllib.request
import zipfile

import psycopg2

MAP = os.getenv('MAP_URL', 'http://localhost:55005')


def _db():
    return psycopg2.connect(
        host=os.getenv('DB_HOST', 'localhost'),
        port=os.getenv('DB_PORT', '55433'),
        dbname='audiotours', user='admin', password='password123')


def _counts(tag):
    conn = _db(); cur = conn.cursor()
    cur.execute("SELECT count(*) FROM audio_tours")
    at = cur.fetchone()[0]
    cur.execute("SELECT count(*) FROM tour_reports")
    tr = cur.fetchone()[0]
    print(f"[row counts {tag}] audio_tours={at}  tour_reports={tr}")
    cur.close(); conn.close()
    return at, tr


def _mini_zip():
    """A minimal valid .zip so store_audio_tour's binary read succeeds."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, 'w') as z:
        z.writestr('tour.txt', 'proof tour audio placeholder')
    import tempfile
    path = tempfile.mktemp(suffix='.zip')
    with open(path, 'wb') as f:
        f.write(buf.getvalue())
    return path


def generate_proof_tour(place, flavour):
    """Generate real tour text with one model call (a genuine generation, not a
    hand-written fixture). `flavour` steers the content so we can exercise a
    general tour and a mature (bar-crawl) tour deterministically."""
    from openai import OpenAI
    client = OpenAI()
    prompt = (f"Write a {flavour} audio-tour script of about 6 short stops for "
              f"{place}. Plain prose, no headings. 400-700 words.")
    resp = client.chat.completions.create(
        model=os.getenv('PROOF_TEXT_MODEL', 'gpt-4o-mini'),
        temperature=0.7,
        messages=[{'role': 'user', 'content': prompt}])
    return resp.choices[0].message.content


def near_rows(adult=False):
    """Query the OWN map-delivery /tours-near and return the tour list."""
    url = f"{MAP}/tours-near/42.3601/-71.0589?radius=50" + ("&adult=1" if adult else "")
    with urllib.request.urlopen(url, timeout=30) as r:
        return json.loads(r.read().decode())['tours']


def row_rating(tour_id):
    conn = _db(); cur = conn.cursor()
    cur.execute("SELECT content_rating, review_status, content_rated_at, "
                "left(content_rating_reason, 80) FROM audio_tours WHERE id = %s",
                (tour_id,))
    row = cur.fetchone()
    cur.close(); conn.close()
    return row


def main():
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import tour_orchestrator_service as orch

    _counts('BEFORE')
    zip_path = _mini_zip()

    # ── Proof A: a general tour is rated general and lists immediately ────────
    print("\n=== Proof A: general tour, rated before listing ===")
    text_a = generate_proof_tour("the Freedom Trail, Boston",
                                 "family-friendly history")
    print(f"generated {len(text_a)} chars of real tour text")
    res_a = orch.store_audio_tour(
        "LOCAL724 Proof Freedom Trail", "boston history walk", zip_path,
        42.3601, -71.0589, tour_content=text_a, stops_count=6, is_test=False,
        user_id="local724proofuser")
    print("store_audio_tour:", {k: res_a[k] for k in ('success', 'action', 'version_no')})

    # ── Proof B: mature content ONLY after char 24,000 -> mature (item 3) ─────
    print("\n=== Proof B: mature only after char 24,000 (item 3) ===")
    filler = generate_proof_tour("the Boston Public Garden", "gentle nature")
    # Pad the general text past 24,000 chars, THEN append a bar-crawl passage.
    head = (filler + "\n") * (24000 // max(1, len(filler)) + 2)
    head = head[:24050]
    tail = ("\n\nFinal stop — the late-night bar crawl: we drink our way through "
            "six pubs, a shot at each, pub crawl rules, heavy drinking, "
            "nightlife and cocktails until 2am.")
    text_b = head + tail
    print(f"text_b length = {len(text_b)} chars; mature passage starts at char "
          f"{text_b.index('bar crawl')}")
    res_b = orch.store_audio_tour(
        "LOCAL724 Proof Late Night", "boston nightlife", zip_path,
        42.3605, -71.0595, tour_content=text_b, stops_count=6, is_test=False)
    print("store_audio_tour:", {k: res_b[k] for k in ('success', 'action')})

    # Give nothing async a chance — rating is synchronous, but settle writes.
    time.sleep(0.5)

    # ── Show the rating AT first /tours-near appearance ───────────────────────
    print("\n=== /tours-near on OWN map-delivery (:55005), no adult flag ===")
    tours = near_rows(adult=False)
    by_name = {t.get('name'): t for t in tours}
    print(f"  {len(tours)} tour(s) listed without adult=1:")
    for name in ("LOCAL724 Proof Freedom Trail", "LOCAL724 Proof Late Night"):
        t = by_name.get(name)
        if t is None:
            print(f"  {name!r}: NOT listed (hidden) without adult=1")
        else:
            print(f"  {name!r}: id={t['id']} content_rating={t.get('content_rating')!r} "
                  f"review_status={t.get('content_review_status')!r}  <-- rated at first appearance")

    print("\n=== /tours-near WITH adult=1 (mature becomes visible only if approved) ===")
    tours_a = near_rows(adult=True)
    names_a = {t.get('name') for t in tours_a}
    print(f"  {len(tours_a)} tour(s) listed with adult=1: "
          f"{sorted(n for n in names_a if n and n.startswith('LOCAL724'))}")

    # Find the ids we just made and print their DB rating (proves rated-at-insert).
    conn = _db(); cur = conn.cursor()
    cur.execute("SELECT id, tour_name, content_rating, review_status FROM audio_tours "
                "WHERE tour_name LIKE 'LOCAL724 Proof%' ORDER BY id")
    made = cur.fetchall(); cur.close(); conn.close()
    print("\n=== DB rating of the tours just created (serving-path rater) ===")
    ids = {}
    for tid, name, cr, rs in made:
        print(f"  id={tid} {name!r} content_rating={cr!r} review_status={rs!r}")
        ids[name] = tid

    # ── Proof C: editing re-rates (item 4) ────────────────────────────────────
    print("\n=== Proof C: edit the general tour's text -> re-rated (item 4) ===")
    fid = ids.get("LOCAL724 Proof Freedom Trail")
    if fid is not None:
        before = row_rating(fid)
        print(f"  before edit: content_rating={before[0]!r} review_status={before[1]!r}")
        # Re-store the SAME tour name with mature text -> orchestrator REPLACE path.
        text_c = ("A pub crawl through Boston: six bars, a shot at each stop, "
                  "heavy drinking and nightlife. " * 40)
        res_c = orch.store_audio_tour(
            "LOCAL724 Proof Freedom Trail", "boston history walk", zip_path,
            42.3601, -71.0589, tour_content=text_c, stops_count=6, is_test=False,
            user_id="local724proofuser")
        print("  store_audio_tour (replace):",
              {k: res_c.get(k) for k in ('success', 'action', 'existing_tour_id')})
        time.sleep(0.5)
        after = row_rating(fid)
        print(f"  after edit:  content_rating={after[0]!r} review_status={after[1]!r} "
              f"rated_at_changed={before[2] != after[2]}")

    _counts('AFTER')
    print("\nDONE.")


if __name__ == '__main__':
    main()
