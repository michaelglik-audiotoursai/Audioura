def breadcrumb(items):
    """items: list of (label, href|None). Last item is current (no link)."""
    lis = []
    for label, href in items:
        if href:
            lis.append('<li><a href="%s">%s</a></li>' % (esc(href), esc(label)))
        else:
            lis.append('<li aria-current="page">%s</li>' % esc(label))
    return ('<nav class="breadcrumb" aria-label="Breadcrumb"><div class="wrap">'
            '<ol>%s</ol></div></nav>\n' % "".join(lis))


def footer():
    return """<footer class="site-footer">
  <div class="wrap">
    <span>&copy; Audioura LLC</span>
    <span><a href="/privacy">Privacy Policy</a> &middot;
      <a href="mailto:info@audioura.com">info@audioura.com</a> &middot;
      <a href="/tours/">All tours</a></span>
  </div>
</footer>
</body>
</html>
"""


def jsonld(obj):
    return ('<script type="application/ld+json">%s</script>\n'
            % json.dumps(obj, ensure_ascii=False, indent=2))


# ─────────────────────────── tour page ──────────────────────────────────────

def tour_url(t):
    return "/tours/%s/%s/" % (t["city_slug"], t["slug"])


def meta_description(t):
    """120–160 char meta description, informed by keyword research."""
    kind = "museum" if t["kind"] == "museum" else "walking"
    if kind == "museum":
        base = ("Free self-guided audio tour of %s — %d masterpieces narrated "
                "in about %d minutes. Listen hands-free in the Audioura app."
                % (t["place_query"], t["stops_count"], t["duration_min"]))
    else:
        base = ("Free self-guided %s audio tour — %d stops in about %d minutes. "
                "Hear %s's stories hands-free in the Audioura app."
                % (t["city"], t["stops_count"], t["duration_min"],
                   t["city"]))
    # trim to <=160 on a word boundary
    if len(base) > 160:
        base = base[:160].rsplit(" ", 1)[0].rstrip(",.;:") + "."
    return base


