# ─────────────────────────── sitemap / robots ───────────────────────────────

def render_sitemap_robots():
    urls = [ORIGIN + "/tours/", ORIGIN + "/pricing/"]
    for city in CITY_ORDER:
        if any(t["city"] == city for t in TOURS):
            urls.append("%s/tours/%s/" % (ORIGIN, city_slug(city)))
    for t in TOURS:
        urls.append(ORIGIN + tour_url(t))
    body = ['<?xml version="1.0" encoding="UTF-8"?>',
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for u in urls:
        body.append("  <url><loc>%s</loc><changefreq>monthly</changefreq>"
                     "</url>" % esc(u))
    body.append("</urlset>\n")
    write("sitemap.xml", "\n".join(body))

    robots = ("User-agent: *\n"
              "Allow: /\n\n"
              "Sitemap: %s/sitemap.xml\n" % ORIGIN)
    write("robots.txt", robots)


def main():
    for t in TOURS:
        render_tour(t)
    for city in CITY_ORDER:
        if any(t["city"] == city for t in TOURS):
            render_city(city)
    render_index()
    render_pricing()
    render_sitemap_robots()
    print("Generated %d tour pages, %d city hubs, index, pricing, sitemap, robots."
          % (len(TOURS), len(set(t["city"] for t in TOURS))))


if __name__ == "__main__":
    main()
