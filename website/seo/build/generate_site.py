def map_block(t):
    """Static, lazy Leaflet map with OSM tiles + attribution. Deferred JS; a
    plain-text stop list already conveys the route without JS (no-JS safe)."""
    pts = [{"lat": s["lat"], "lng": s["lng"], "title": s["title"], "n": s["num"]}
           for s in t["stops"]]
    data = json.dumps({"center": [t["lat"], t["lng"]], "points": pts},
                      ensure_ascii=False)
    return """<section class="map-wrap" aria-labelledby="map-h">
  <h2 id="map-h">Route map</h2>
  <div id="map" role="img"
       aria-label="Map of the {n} stops on the {name} route"></div>
  <p class="map-fallback">Map &copy; OpenStreetMap contributors. The full
    turn-by-turn route is guided by voice in the app.</p>
</section>
<script>window.__TOUR__ = {data};</script>
<script defer src="/assets/js/map.js"></script>
""".format(n=t["stops_count"], name=esc(t["short_title"]), data=data)


def tour_jsonld(t, faq, sample_url, canonical):
    attractions = []
    for s in t["stops"]:
        item = {
            "@type": "TouristAttraction",
            "name": s["title"],
            "geo": {"@type": "GeoCoordinates",
                    "latitude": s["lat"], "longitude": s["lng"]},
        }
        if s.get("address"):
            item["address"] = s["address"]
        attractions.append(item)
    trip = {
        "@context": "https://schema.org",
        "@type": "TouristTrip",
        "name": t["h1"],
        "description": meta_description(t),
        "url": canonical,
        "touristType": "Self-guided audio tour",
        "itinerary": {
            "@type": "ItemList",
            "numberOfItems": len(attractions),
            "itemListElement": [
                {"@type": "ListItem", "position": i + 1, "item": a}
                for i, a in enumerate(attractions)
            ],
        },
        "subjectOf": {
            "@type": "AudioObject",
            "name": "%s — 45-second sample" % t["short_title"],
            "contentUrl": sample_url,
            "encodingFormat": "audio/mpeg",
            "description": "A 45-second preview of the first stop's narration.",
        },
        "provider": {
            "@type": "Organization",
            "name": "Audioura",
            "url": ORIGIN + "/",
        },
    }
    crumbs = {
        "@context": "https://schema.org",
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Tours",
             "item": ORIGIN + "/tours/"},
            {"@type": "ListItem", "position": 2, "name": t["city"],
             "item": "%s/tours/%s/" % (ORIGIN, t["city_slug"])},
            {"@type": "ListItem", "position": 3, "name": t["short_title"],
             "item": canonical},
        ],
    }
    faqpage = {
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "mainEntity": [
            {"@type": "Question", "name": q,
             "acceptedAnswer": {"@type": "Answer", "text": a}}
            for q, a in faq
        ],
    }
    return jsonld(trip) + jsonld(crumbs) + jsonld(faqpage)


def intro_paragraph(t):
    if t["kind"] == "museum":
        return ("This free, self-guided audio tour walks you through %d of the "
                "most remarkable works at %s. Press play at the first stop and "
                "let Audioura narrate each piece — its history, its maker and "
                "why it matters — while you look, not at your phone. The whole "
                "route takes about %d minutes."
                % (t["stops_count"], t["place_query"], t["duration_min"]))
    dist = (" over roughly %s km" % _fmt_km(t["distance_km"])
            if t["distance_km"] else "")
    return ("This free, self-guided %s audio tour links %d landmarks%s through "
            "%s. Audioura guides you stop to stop by voice and tells each "
            "place's story as you arrive, so you can keep your eyes on the "
            "city. Allow about %d minutes at an easy pace."
            % (t["city"], t["stops_count"], dist, t["city"],
               t["duration_min"]))


def _fmt_km(km):
    return ("%.1f" % km).rstrip("0").rstrip(".")


def render_tour(t):
    canonical = ORIGIN + tour_url(t)
    og = "%s/assets/og/%s.png" % (ORIGIN, t["slug"])
    sample_rel = "/assets/audio/%s-sample.mp3" % t["slug"]
    sample_url = ORIGIN + sample_rel
    title = "%s | Audioura" % t["h1"]
    desc = meta_description(t)
    faq = build_faq(t, KEYWORDS.get(t["source_id"], {}))

    parts = [head(title, desc, canonical, og, og_type="article")]
    parts.append(header_nav())
    parts.append(breadcrumb([
        ("Tours", "/tours/"),
        (t["city"], "/tours/%s/" % t["city_slug"]),
        (t["short_title"], None),
    ]))
    parts.append('<main id="main"><div class="wrap">\n')
    parts.append("<h1>%s</h1>\n" % esc(t["h1"]))

    # meta pills
    pills = ['<span class="pill"><strong>%d</strong> stops</span>' % t["stops_count"],
             '<span class="pill"><strong>~%d</strong> min</span>' % t["duration_min"]]
    if t["distance_km"]:
        pills.append('<span class="pill"><strong>%s</strong> km</span>'
                     % _fmt_km(t["distance_km"]))
    pills.append('<span class="pill">Self-guided</span>')
    pills.append('<span class="pill">%s, %s</span>'
                 % (esc(t["city"]), esc(t["country"])))
    parts.append('<div class="meta-row">%s</div>\n' % "".join(pills))

    parts.append('<p class="lede">%s</p>\n' % esc(intro_paragraph(t)))

    # audio sample
    parts.append("""<section class="sample" aria-labelledby="sample-h">
  <h2 id="sample-h">Listen — 45-second sample</h2>
  <p>A taste of the first stop. The full tour is narrated in the app.</p>
  <audio controls preload="none" src="{src}">
    Your browser does not support audio playback.
    <a href="{src}">Download the sample (MP3)</a>.
  </audio>
</section>
""".format(src=esc(sample_rel)))

    # store buttons
    parts.append('<section aria-labelledby="get-h"><h2 id="get-h">'
                 'Listen on the app</h2>\n')
    parts.append(store_buttons())
    parts.append("</section>\n")

    # stops
    parts.append('<section aria-labelledby="stops-h">\n')
    parts.append('<h2 id="stops-h">What you\'ll hear — %d stops</h2>\n'
                 % t["stops_count"])
    parts.append('<ol class="stops">\n')
    for s in t["stops"]:
        teaser = make_teaser(s["story_source"], s["title"], s["type"])
        typ = ('<span class="stop-type">%s</span>' % esc(s["type"])
               if s["type"] and s["type"].lower() != "none" else "")
        parts.append('  <li><h3>%s</h3>%s<p>%s</p></li>\n'
                     % (esc(s["title"]), typ, esc(teaser)))
    parts.append("</ol>\n</section>\n")

    # map
    parts.append(map_block(t))

    # FAQ
    parts.append('<section class="faq" aria-labelledby="faq-h">\n')
    parts.append('<h2 id="faq-h">Frequently asked questions</h2>\n')
    for q, a in faq:
        parts.append('<details><summary>%s</summary><p>%s</p></details>\n'
                     % (esc(q), esc(a)))
    parts.append("</section>\n")

    parts.append("</div></main>\n")
    parts.append(tour_jsonld(t, faq, sample_url, canonical))
    parts.append(footer())
    write(tour_url(t).lstrip("/") + "index.html", "".join(parts))


