def render_city(city):
    cslug = city_slug(city)
    tours = [t for t in TOURS if t["city"] == city]
    canonical = "%s/tours/%s/" % (ORIGIN, cslug)
    title = "%s audio tours — self-guided & hands-free | Audioura" % city
    desc = ("Self-guided audio tours in %s: %s. Free, hands-free, narrated "
            "stop by stop in the Audioura app."
            % (city, ", ".join(t["short_title"].split(" — ")[0]
                                for t in tours)))
    if len(desc) > 160:
        desc = desc[:157].rsplit(" ", 1)[0] + "…"
    og = "%s/assets/og/%s.png" % (ORIGIN, tours[0]["slug"])

    parts = [head(title, desc, canonical, og)]
    parts.append(header_nav())
    parts.append(breadcrumb([("Tours", "/tours/"), (city, None)]))
    parts.append('<main id="main"><div class="wrap">\n')
    parts.append("<h1>%s audio tours</h1>\n" % esc(city))
    parts.append('<p class="lede">%s</p>\n' % esc(CITY_BLURB.get(city, "")))
    parts.append('<div class="card-grid">\n')
    for t in tours:
        parts.append(_tour_card(t))
    parts.append("</div>\n")
    parts.append('<p><a href="/tours/">&larr; All destinations</a></p>\n')
    parts.append("</div></main>\n")
    # BreadcrumbList + ItemList JSON-LD
    parts.append(jsonld({
        "@context": "https://schema.org",
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Tours",
             "item": ORIGIN + "/tours/"},
            {"@type": "ListItem", "position": 2, "name": city,
             "item": canonical},
        ],
    }))
    parts.append(jsonld({
        "@context": "https://schema.org",
        "@type": "ItemList",
        "itemListElement": [
            {"@type": "ListItem", "position": i + 1,
             "url": ORIGIN + tour_url(t), "name": t["h1"]}
            for i, t in enumerate(tours)
        ],
    }))
    parts.append(footer())
    write("tours/%s/index.html" % cslug, "".join(parts))


def _tour_card(t):
    bits = ["%d stops" % t["stops_count"], "~%d min" % t["duration_min"]]
    if t["distance_km"]:
        bits.append("%s km" % _fmt_km(t["distance_km"]))
    return ("""  <a class="card" href="{url}">
    <img class="card-art" src="/assets/og/{slug}.png" alt="" width="1200"
         height="630" loading="lazy">
    <span class="card-body">
      <h3>{name}</h3>
      <span class="card-sub">{city}, {country}</span>
      <span class="card-meta">{meta}</span>
    </span>
  </a>
""".format(url=tour_url(t), slug=t["slug"],
           name=esc(t["short_title"]), city=esc(t["city"]),
           country=esc(t["country"]), meta=esc(" · ".join(bits))))


