def esc(s):
    return html.escape(str(s), quote=True)


def write(path, content):
    full = os.path.join(SITE, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8") as fh:
        fh.write(content)
    return full


def city_slug(city):
    for t in TOURS:
        if t["city"] == city:
            return t["city_slug"]
    return city.lower().replace(" ", "-")


