#!/usr/bin/env python3
"""
Community Tours Service (LOCAL-701, D663 §3)

A tour made with Audioura FOR a community. The organiser (owner of ≥1 community)
chooses "For: my community <name>" on the Generate tab; the tour is generated by
the SAME pipeline as any tour (D656 content rating + review queue), CHARGED to
the organiser's plan allowance (the generate path already charges the requesting
user — the organiser IS that user), and then TAGGED onto the community:

    audio_tours.community_id          — the owning community (NULL = ordinary tour)
    audio_tours.community_visibility  — 'members' (default) | 'public'

Visibility rules (enforced here + in map_delivery):
  * members  — never on /tours-near or /search-tours; shows on the community
               page like an episode; only an ACTIVE member downloads it.
  * public   — on the map/search WITH the community badge (requires coordinates),
               but download requires an active membership — a non-member gets
               402 {"error":"membership_required","community_id":…} and the app
               opens the community page (join / buy pass), same flow as a paid
               tour. Members download free of extra charge (the pass is the
               payment; D660 per-download rules do NOT apply to community tours).

This module owns the SERVER side of tagging a generated tour to a community and
reading a community's tours. It is DELIBERATELY self-contained apart from the
shared test DB helper (same pattern as tour_pricing_service.py), so it can be
registered on the orchestrator and imported by a test without pulling in Flask
at import time.

Design decisions documented in SUBMISSION_LOCAL-701.md.
"""

import os
import sys

# Reuse the shared DB connection helper the other services use (tests/).
sys.path.insert(0, os.path.join(os.path.dirname(__file__), 'tests'))
from db_connection import get_connection  # noqa: E402


# The two allowed visibilities. 'members' is the DEFAULT (D663 §3: members-only
# by default); 'public' needs coordinates and shows on the map with the badge.
VALID_VISIBILITIES = ('members', 'public')
DEFAULT_VISIBILITY = 'members'


class CommunityTourError(Exception):
    """Raised with a stable `code` so a route maps it to the right HTTP status.

    code ∈ 'unknown_community' (404) | 'not_owner' (403) |
           'bad_visibility' (400) | 'unknown_tour' (404) |
           'public_needs_location' (400).
    """

    def __init__(self, code, message):
        super().__init__(message)
        self.code = code
        self.message = message


# ─── Schema probe (cached) ────────────────────────────────────────────────────
_HAS_COMMUNITY_COLUMNS = None


def has_community_columns(cur):
    """True if audio_tours.community_id + community_visibility exist (migration
    035). Probed once per process and cached. Absent (older schema) → tagging is
    a no-op and every tour reads as an ordinary public tour — the feature fails
    OFF, never a 500."""
    global _HAS_COMMUNITY_COLUMNS
    if _HAS_COMMUNITY_COLUMNS is None:
        try:
            cur.execute(
                "SELECT COUNT(*) FROM information_schema.columns "
                "WHERE table_name = 'audio_tours' "
                "AND column_name IN ('community_id', 'community_visibility')"
            )
            _HAS_COMMUNITY_COLUMNS = (cur.fetchone()[0] == 2)
        except Exception:  # noqa: BLE001
            _HAS_COMMUNITY_COLUMNS = False
    return _HAS_COMMUNITY_COLUMNS


# ─── Ownership + membership ───────────────────────────────────────────────────

def community_owner(cur, community_id):
    """The owner_user_id of a community, or None when it does not exist / is
    disabled. A disabled community cannot be a tour target (it lists nothing)."""
    try:
        cur.execute(
            "SELECT owner_user_id, disabled FROM communities WHERE id = %s",
            (int(community_id),),
        )
        row = cur.fetchone()
    except Exception:  # noqa: BLE001 — communities table absent → no owner
        return None
    if not row or row[1]:  # missing or disabled
        return None
    return row[0]


def is_community_owner(cur, user_id, community_id):
    """True iff user_id owns the (non-disabled) community."""
    owner = community_owner(cur, community_id)
    return owner is not None and str(owner) == str(user_id)


def is_active_member(cur, user_id, community_id, now=None):
    """True iff user_id is an ACTIVE member of the community (free membership
    with NULL expiry, or a paid membership not yet expired), OR the OWNER.

    This is the single gate for "may this user get a community tour?" — the
    owner always may (they made it), a member may while their pass is live. A
    non-member or an expired member may not. Mirrors
    communities_api.is_membership_active but reads the row here so this module
    needs no cross-import at the orchestrator. Never raises → False on error
    (fail closed: a lookup problem must not hand out community content)."""
    if not user_id:
        return False
    from datetime import datetime
    now = now or datetime.utcnow()
    try:
        if is_community_owner(cur, user_id, community_id):
            return True
        cur.execute(
            "SELECT expires_at FROM community_memberships "
            "WHERE user_id = %s AND community_id = %s",
            (str(user_id), int(community_id)),
        )
        row = cur.fetchone()
        if row is None:
            return False  # not a member at all
        expires_at = row[0]
        return expires_at is None or expires_at > now
    except Exception:  # noqa: BLE001
        return False


# ─── Tagging a generated tour onto a community ────────────────────────────────

def normalise_visibility(visibility):
    """Return a valid visibility string, defaulting to 'members'. Raises
    CommunityTourError('bad_visibility') on an unrecognised value (never
    silently coerce an unknown value to public — members-only is the safe
    default)."""
    if visibility is None or str(visibility).strip() == '':
        return DEFAULT_VISIBILITY
    v = str(visibility).strip().lower()
    if v not in VALID_VISIBILITIES:
        raise CommunityTourError(
            'bad_visibility',
            "community_visibility must be 'members' or 'public'.",
        )
    return v


def _tour_has_coordinates(cur, tour_id):
    """True iff the tour row carries lat AND lng. A PUBLIC community tour needs
    coordinates (it shows on the map); a members-only one does not."""
    try:
        cur.execute(
            "SELECT lat, lng FROM audio_tours WHERE id = %s", (int(tour_id),)
        )
        row = cur.fetchone()
    except Exception:  # noqa: BLE001
        return False
    return bool(row and row[0] is not None and row[1] is not None)


def tag_community_tour(cur, tour_id, community_id, visibility=DEFAULT_VISIBILITY,
                       owner_user_id=None):
    """Tag an already-stored tour as belonging to a community. Cursor form, so
    the orchestrator calls it inside its own post-store transaction (no commit
    here — the caller owns the transaction).

    Validations (in order):
      * the columns must exist (else a quiet no-op → returns False; the feature
        is simply off on a schema that predates migration 035);
      * the community must exist and not be disabled — else 'unknown_community';
      * when owner_user_id is given, they must OWN the community — else
        'not_owner' (the organiser can only tag onto their own community);
      * the tour must exist — else 'unknown_tour';
      * a PUBLIC tour must have coordinates — else 'public_needs_location'.

    Writes community_id + community_visibility on the ORIGINAL tour row. Returns
    True when a row was tagged.
    """
    if not has_community_columns(cur):
        return False

    vis = normalise_visibility(visibility)

    owner = community_owner(cur, community_id)
    if owner is None:
        raise CommunityTourError(
            'unknown_community',
            f"No open community with id {community_id}.",
        )
    if owner_user_id is not None and str(owner) != str(owner_user_id):
        raise CommunityTourError(
            'not_owner',
            "You can only publish a tour to a community you own.",
        )

    cur.execute("SELECT 1 FROM audio_tours WHERE id = %s", (int(tour_id),))
    if cur.fetchone() is None:
        raise CommunityTourError('unknown_tour', f"No tour with id {tour_id}.")

    if vis == 'public' and not _tour_has_coordinates(cur, tour_id):
        raise CommunityTourError(
            'public_needs_location',
            "A public community tour needs coordinates to show on the map.",
        )

    cur.execute(
        "UPDATE audio_tours SET community_id = %s, community_visibility = %s "
        "WHERE id = %s",
        (int(community_id), vis, int(tour_id)),
    )
    return True


# ─── Reads ────────────────────────────────────────────────────────────────────

def community_tour_tag(cur, tour_id):
    """{community_id, community_visibility} for a tour (resolving a translation
    to its original), or {community_id: None, community_visibility: None} for an
    ordinary tour / older schema. Used by the download gate and the app's Origin
    menu."""
    out = {'community_id': None, 'community_visibility': None}
    if not has_community_columns(cur):
        return out
    try:
        cur.execute(
            "SELECT COALESCE(orig.community_id, t.community_id), "
            "       COALESCE(orig.community_visibility, t.community_visibility) "
            "FROM audio_tours t "
            "LEFT JOIN audio_tours orig ON orig.id = t.original_tour_id "
            "WHERE t.id = %s",
            (int(tour_id),),
        )
        row = cur.fetchone()
    except Exception:  # noqa: BLE001
        return out
    if row and row[0] is not None:
        out['community_id'] = int(row[0])
        out['community_visibility'] = row[1]
    return out


def list_community_tours(cur, community_id):
    """Every tour tagged to a community (both members-only and public), newest
    first, as a list of dicts the community page renders:
        {id, name, request_string, lat, lng, visibility, content_rating}
    Originals only (a translation inherits the tag; we list the governing row).
    Content-rating columns read through COALESCE so a NULL rating shows as the
    app's 'general'. Empty list on an older schema / error."""
    if not has_community_columns(cur):
        return []
    try:
        cur.execute(
            "SELECT id, tour_name, request_string, lat, lng, community_visibility, "
            "       content_rating "
            "FROM audio_tours "
            "WHERE community_id = %s AND original_tour_id IS NULL "
            "ORDER BY id DESC",
            (int(community_id),),
        )
        rows = cur.fetchall()
    except Exception:  # noqa: BLE001 — content_rating may be absent on old schema
        try:
            cur.connection.rollback()
        except Exception:
            pass
        try:
            cur.execute(
                "SELECT id, tour_name, request_string, lat, lng, "
                "community_visibility "
                "FROM audio_tours WHERE community_id = %s AND original_tour_id IS NULL "
                "ORDER BY id DESC",
                (int(community_id),),
            )
            rows = [(r[0], r[1], r[2], r[3], r[4], None) for r in cur.fetchall()]
        except Exception:  # noqa: BLE001
            return []
    out = []
    for r in rows:
        out.append({
            'id': r[0],
            'name': r[1],
            'request_string': r[2],
            'lat': r[3],
            'lng': r[4],
            'visibility': r[5],
            'content_rating': (r[6] or 'general') if len(r) > 6 else 'general',
        })
    return out


def community_tours_for_member(user_id, community_id):
    """The community page's tour list, gated by membership. Returns a dict:
        {community_id, is_member, tours}
    `tours` is the full list ONLY for an active member or the owner; a
    non-member / expired member gets an EMPTY list (expiry blocks NEW content,
    D658 §2 — the same rule the episode list uses). The community page still
    renders (name, passes, join button) from communities_api; this only decides
    whether the episode-like tour list is populated."""
    conn = get_connection()
    try:
        cur = conn.cursor()
        active = is_active_member(cur, user_id, community_id)
        tours = list_community_tours(cur, community_id) if active else []
        return {
            'community_id': int(community_id),
            'is_member': bool(active),
            'tours': tours,
        }
    finally:
        conn.close()


def public_community_tours(cur, community_ids=None):
    """{tour_id: community_id} for PUBLIC community tours (for the map badge).

    map_delivery already lists public tours; this tells it which carry a
    community badge and which community they belong to. Restrict to
    `community_ids` when given (the communities currently in view), else all.
    Empty on an older schema."""
    if not has_community_columns(cur):
        return {}
    try:
        if community_ids:
            cur.execute(
                "SELECT id, community_id FROM audio_tours "
                "WHERE community_visibility = 'public' AND community_id = ANY(%s) "
                "AND original_tour_id IS NULL",
                (sorted({int(c) for c in community_ids}),),
            )
        else:
            cur.execute(
                "SELECT id, community_id FROM audio_tours "
                "WHERE community_visibility = 'public' AND community_id IS NOT NULL "
                "AND original_tour_id IS NULL"
            )
        return {int(tid): int(cid) for tid, cid in cur.fetchall()}
    except Exception:  # noqa: BLE001
        return {}


# ─── Download gate decision (D663 §3) ─────────────────────────────────────────

def community_download_decision(cur, user_id, tour_id, now=None):
    """The community-tour part of the download gate for ONE tour.

    Returns (relevant: bool, allowed: bool, deny: dict|None):
      * relevant=False — this is NOT a community tour; the caller applies the
        ordinary paid/free gate unchanged.
      * relevant=True, allowed=True — a community tour the user may download
        (an active member or the owner). D660 per-download rules do NOT apply:
        the pass is the payment, members re-download free.
      * relevant=True, allowed=False — a community tour the user may NOT
        download. `deny` is the 402 body:
            {"error":"membership_required","community_id":…,"tour_id":…}
        The app opens the community page (join / buy pass), the same flow as a
        paid tour.
    """
    tag = community_tour_tag(cur, tour_id)
    community_id = tag['community_id']
    if community_id is None:
        return False, True, None  # not a community tour — ordinary gate applies
    if is_active_member(cur, user_id, community_id, now=now):
        return True, True, None
    return True, False, {
        "error": "membership_required",
        "community_id": int(community_id),
        "tour_id": int(tour_id),
    }


# ─── Flask API routes (registered on the orchestrator) ────────────────────────

def register_community_tour_routes(app):
    """Register the community-tour endpoints on a Flask app (the orchestrator).

    Endpoints:
        POST /tour/<tour_id>/community   {user_id, community_id, visibility}
             → tag an own tour onto an own community (organiser), set visibility.
        GET  /tour/<tour_id>/community   → the tour's {community_id, visibility}.
        GET  /communities/<community_id>/tours?user_id=...
             → the community's tour list (populated for members/owner only).
    """
    from flask import request, jsonify

    _status_for = {
        'unknown_community': 404,
        'not_owner': 403,
        'bad_visibility': 400,
        'unknown_tour': 404,
        'public_needs_location': 400,
    }

    @app.route('/tour/<int:tour_id>/community', methods=['POST'])
    def api_tag_community_tour(tour_id):
        data = request.get_json(silent=True) or {}
        user_id = data.get('user_id')
        community_id = data.get('community_id')
        if not user_id:
            return jsonify({"error": "user_id is required"}), 400
        if community_id is None:
            return jsonify({"error": "community_id is required"}), 400
        visibility = data.get('visibility') or data.get('community_visibility')
        conn = get_connection()
        try:
            cur = conn.cursor()
            try:
                tagged = tag_community_tour(cur, tour_id, community_id,
                                           visibility=visibility,
                                           owner_user_id=user_id)
            except CommunityTourError as e:
                conn.rollback()
                return jsonify({"error": e.code, "message": e.message}), \
                    _status_for.get(e.code, 400)
            if not tagged:
                conn.rollback()
                return jsonify({"error": "community_tours_unavailable",
                                "message": "Community tours are not enabled on "
                                           "this server."}), 503
            conn.commit()
            tag = community_tour_tag(cur, tour_id)
            return jsonify({"status": "ok", "tour_id": int(tour_id), **tag}), 200
        except Exception as e:  # noqa: BLE001
            conn.rollback()
            return jsonify({"error": str(e)}), 500
        finally:
            conn.close()

    @app.route('/tour/<int:tour_id>/community', methods=['GET'])
    def api_get_community_tour(tour_id):
        conn = get_connection()
        try:
            cur = conn.cursor()
            tag = community_tour_tag(cur, tour_id)
            return jsonify({"tour_id": int(tour_id), **tag}), 200
        except Exception as e:  # noqa: BLE001
            return jsonify({"error": str(e)}), 500
        finally:
            conn.close()

    @app.route('/communities/<int:community_id>/tours', methods=['GET'])
    def api_community_tours(community_id):
        user_id = request.args.get('user_id')
        try:
            result = community_tours_for_member(user_id, community_id)
        except Exception as e:  # noqa: BLE001
            return jsonify({"error": str(e)}), 500
        return jsonify(result), 200
